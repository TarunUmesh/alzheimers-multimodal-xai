"""Turn the numbers produced by the models into plain-language reasons.

Nothing here is generated by a language model: every sentence is produced by a
fixed rule from a measured quantity, so the same input always gives the same
explanation and each sentence can be traced back to its evidence.
"""
from __future__ import annotations

import config

ZONE_TEXT = {
    "central": (
        "the centre of the brain slice, where the fluid-filled ventricles are",
        "In Alzheimer's disease the brain tissue shrinks and the ventricles become larger, "
        "so this is an area where a difference between healthy and affected brains is expected.",
    ),
    "outer_cortex": (
        "the outer edge of the brain (the cortex)",
        "Thinning of the cortex and widening of its grooves is a sign of tissue loss (atrophy) "
        "seen as Alzheimer's disease progresses.",
    ),
    "deep_middle": (
        "the tissue between the centre and the outer edge",
        "This area holds the white matter and deeper structures; loss of volume here also "
        "accompanies the disease.",
    ),
}


def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


# --------------------------------------------------------------------------
# MRI
# --------------------------------------------------------------------------
def explain_mri(mri: dict) -> list[dict]:
    reasons = []
    probs = sorted(mri["probabilities"].items(), key=lambda kv: kv[1], reverse=True)
    (top, p_top), (second, p_second) = probs[0], probs[1]
    text = (f"The MRI model classified the scan as {config.MRI_CLASS_LABELS[top]} "
            f"with {_pct(p_top)} confidence. The next most likely class was "
            f"{config.MRI_CLASS_LABELS[second]} ({_pct(p_second)}).")
    reasons.append({"source": "MRI", "kind": "prediction", "text": text})

    if p_top < 0.60:
        reasons.append({"source": "MRI", "kind": "caution", "text":
                        f"The confidence is low ({_pct(p_top)}), so the model is undecided between "
                        "neighbouring stages. Treat the stage as approximate."})

    regions = mri.get("regions") or {}
    zones = regions.get("zones") or {}
    if not regions.get("reliable", True):
        reasons.append({"source": "MRI", "kind": "caution", "text":
                        "Heat-map check failed: " + regions.get("note", "the heat-map could not be analysed.")})
    elif zones:
        ranked = sorted(((n, zones[n]) for n in ZONE_TEXT), key=lambda kv: kv[1]["focus"], reverse=True)
        name, z = ranked[0]
        where, why = ZONE_TEXT[name]
        if z["focus"] >= 1.15:
            text = (f"The Grad-CAM heat-map shows the model relied most on {where}: {_pct(z['heat_share'])} of the "
                    f"attention fell there although it covers only {_pct(z['area_share'])} of the brain area. {why}")
        else:
            text = ("The Grad-CAM heat-map is spread fairly evenly over the brain; the model did not rely on "
                    "one particular area.")
        if mri["predicted_class"] == "NonDemented" and z["focus"] >= 1.15:
            text += " Here the model examined that area and did not find the pattern it associates with dementia."
        reasons.append({"source": "MRI", "kind": "evidence", "text": text})

        left, right = zones["image_left"]["heat_share"], zones["image_right"]["heat_share"]
        if abs(left - right) >= 0.25:
            side = "left" if left > right else "right"
            reasons.append({"source": "MRI", "kind": "evidence", "text":
                            f"The attention was clearly stronger on the {side} half of the image "
                            f"({_pct(max(left, right))} against {_pct(min(left, right))})."})

    reasons.append({"source": "MRI", "kind": "note", "text":
                    "Grad-CAM shows where the model looked, not a medical finding. The image areas are "
                    "approximate zones on a 2-D slice, not an anatomical measurement."})
    return reasons


# --------------------------------------------------------------------------
# Speech
# --------------------------------------------------------------------------
def _marker_sentence(m: dict) -> str:
    value, ref = m["value"], m.get("control_mean")
    fmt = (lambda v: f"{v:.0f}") if m["name"] == "word_count" else (lambda v: f"{v:.2f}") \
        if m["unit"].startswith("0-1") else (lambda v: f"{v:.1f}")
    unit = "" if m["unit"].startswith("0-1") else " " + m["unit"]
    return f"{m['label']}: {fmt(value)}{unit} (control group average {fmt(ref)})"


def explain_speech(speech: dict) -> list[dict]:
    reasons = []
    p = speech["p_dementia"]
    if speech["predicted_class"] == "Dementia":
        text = (f"The speech model judged the language pattern to be closer to the Dementia group "
                f"(probability {_pct(p)}).")
    else:
        text = (f"The speech model judged the language pattern to be closer to the healthy Control group "
                f"(probability of dementia {_pct(p)}).")
    reasons.append({"source": "Speech", "kind": "prediction", "text": text})

    towards = [m for m in speech["markers"] if m["flag"] == "towards_dementia"]
    against = [m for m in speech["markers"] if m["flag"] == "towards_control"]
    if towards:
        reasons.append({"source": "Speech", "kind": "evidence", "text":
                        "Speech markers that differ from healthy speakers: "
                        + "; ".join(_marker_sentence(m) for m in towards) + "."})
    if against:
        reasons.append({"source": "Speech", "kind": "evidence", "text":
                        "Speech markers that look healthy: "
                        + "; ".join(_marker_sentence(m) for m in against) + "."})
    if not towards and not against:
        reasons.append({"source": "Speech", "kind": "evidence", "text":
                        "All measured speech markers were within the usual range of the control group."})

    words = [w for w in speech["word_contributions"] if abs(w["contribution"]) >= 0.01]
    up = [w["word"] for w in words if w["contribution"] > 0][:6]
    down = [w["word"] for w in words if w["contribution"] < 0][:6]
    if up:
        reasons.append({"source": "Speech", "kind": "evidence", "text":
                        "Words that raised the dementia probability most: " + ", ".join(f'"{w}"' for w in up) + "."})
    if down:
        reasons.append({"source": "Speech", "kind": "evidence", "text":
                        "Words that lowered it most: " + ", ".join(f'"{w}"' for w in down) + "."})

    timing = speech.get("timing")
    if timing and timing.get("words_per_minute"):
        wpm = timing["words_per_minute"]
        text = f"From the recording: speaking rate {wpm:.0f} words per minute"
        text += " (slower than the roughly 120-160 typical of fluent speech)" if wpm < 100 else ""
        text += f", {timing['long_pauses']} pause(s) of 2 seconds or longer"
        text += f" (longest {timing['longest_pause']:.1f} s)." if timing["long_pauses"] else "."
        text += " These timing figures are shown for information; the classifier itself uses only the words."
        reasons.append({"source": "Speech", "kind": "evidence", "text": text})

    if speech.get("too_short"):
        reasons.append({"source": "Speech", "kind": "caution", "text":
                        f"The sample is short ({speech['word_count']} words). About a minute of speech "
                        "(100 words or more) gives a much more dependable result."})
    if speech.get("model_meta", {}).get("is_synthetic"):
        reasons.append({"source": "Speech", "kind": "caution", "text":
                        "The speech model in use was trained on the synthetic demo transcripts, not on real "
                        "patient speech. Its output demonstrates the pipeline only. Retrain on DementiaBank "
                        "before drawing any conclusion from it."})
    return reasons


# --------------------------------------------------------------------------
# Fusion
# --------------------------------------------------------------------------
def explain_fusion(fusion: dict) -> list[dict]:
    reasons = []
    score, level = fusion["risk_score"], fusion["risk_level"]
    if fusion["agreement"] == "single":
        only = fusion["modalities_used"][0]
        other = "speech sample" if only == "MRI" else "MRI scan"
        reasons.append({"source": "Combined", "kind": "prediction", "text":
                        f"Overall risk score {_pct(score)} ({level}), based on the {only} result only. "
                        f"Adding a {other} would allow the two to be cross-checked."})
        return reasons

    w = fusion["weights"]
    reasons.append({"source": "Combined", "kind": "prediction", "text":
                    f"Overall risk score {_pct(score)} ({level}) = "
                    f"{w['mri']:.2f} x MRI ({_pct(fusion['p_mri_impaired'])}) + "
                    f"{w['speech']:.2f} x speech ({_pct(fusion['p_speech_dementia'])})."})
    if fusion["agreement"] == "both_positive":
        text = ("The brain scan and the speech sample point the same way: both show signs associated with "
                "dementia. Two independent kinds of evidence agreeing makes the result more credible than "
                "either alone.")
    elif fusion["agreement"] == "both_negative":
        text = ("The brain scan and the speech sample agree: neither shows the pattern associated with "
                "dementia.")
    elif fusion["p_mri_impaired"] >= 0.5:
        text = ("The two results disagree: the scan shows changes but the speech sounds healthy. This can "
                "happen early on, when structural change comes before noticeable language difficulty, or it "
                "can be a model error. A clinical assessment is needed to settle it.")
    else:
        text = ("The two results disagree: the speech shows difficulties but the scan looks normal. Speech can "
                "be affected by many things other than dementia (tiredness, anxiety, hearing, a second "
                "language, a poor recording), or it can be a model error. A clinical assessment is needed "
                "to settle it.")
    reasons.append({"source": "Combined", "kind": "evidence", "text": text})
    return reasons


def explain_all(mri: dict | None, speech: dict | None, fusion: dict) -> list[dict]:
    reasons = explain_fusion(fusion)
    if mri is not None:
        reasons += explain_mri(mri)
    if speech is not None:
        reasons += explain_speech(speech)
    return reasons
